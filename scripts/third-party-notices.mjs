/** Production packages as installed: name, version and directory, without duplicates. */
function productionPackages() {
  const out = execFileSync('npm', ['ls', '--omit=dev', '--all', '--parseable'], {
    cwd: root,
    encoding: 'utf8',
  });
  const seen = new Map();
  for (const dir of out.split('\n').slice(1).filter(Boolean)) {
    const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
    const key = `${pkg.name}@${pkg.version}`;
    if (!seen.has(key)) seen.set(key, { dir, pkg });
  }
  return [...seen.values()];
}

/** Type declarations are never part of the bundle. */
function typesOnly(pkg) {
  if (pkg.name.startsWith('@types/')) return true;
  return !pkg.main && !pkg.module && !pkg.exports && !pkg.browser && Boolean(pkg.types);
}

function licenceFiles(dir) {
  return readdirSync(dir)
    .filter((f) => /^(licen[cs]e|copying|notice)(\.(md|txt))?$/i.test(f))
    .sort();
}

const rule = '='.repeat(78);
const thin = '-'.repeat(78);

export function buildNotices() {
  const packages = productionPackages()
    .filter(({ pkg }) => !typesOnly(pkg))
    .sort(
      (a, b) =>
        a.pkg.name.localeCompare(b.pkg.name, 'en') || a.pkg.version.localeCompare(b.pkg.version),
    );
  const parts = [
    'Graticule: third-party notices',
    '',
    'The Graticule web application includes the software and fonts listed below,',
    'each under its own licence. Their copyright notices and licence texts are',
    "reproduced here as those licences require. Graticule's own licence is in the",
    'LICENSE file of its repository.',
    '',
    'This file is generated by scripts/third-party-notices.mjs (npm run notices).',
    '',
    rule,
    'Fira Sans and Fira Sans Condensed (fonts)',
    'Licence: SIL Open Font License 1.1',
    thin,
    readFileSync(join(root, 'src', 'assets', 'fonts', 'OFL.txt'), 'utf8').trim(),
  ];
  for (const { dir, pkg } of packages) {
    const licence = typeof pkg.license === 'string' ? pkg.license : JSON.stringify(pkg.license);
    parts.push('', rule, `${pkg.name} ${pkg.version}`, `Licence: ${licence}`);
    const files = licenceFiles(dir);
    if (files.length === 0) {
      if (licence !== 'MIT') throw new Error(`${pkg.name} ships no licence file and is not MIT.`);
      const author = typeof pkg.author === 'string' ? pkg.author : pkg.author?.name;
      parts.push(
        thin,
        `This package ships no licence file. Its package.json declares the MIT licence${author ? `, with author ${author.replace(/\s*<[^>]*>/, '')}` : ''}${
          pkg.contributors?.length
            ? ` and ${pkg.contributors.length === 1 ? 'contributor' : 'contributors'} ${pkg.contributors
                .map((c) => (typeof c === 'string' ? c : c.name).replace(/\s*[<(].*$/, ''))
                .join(', ')}`
            : ''
        }. The MIT licence text follows.`,
        '',
        MIT_TEXT,
      );
    }
    for (const f of files)
      parts.push(thin, readFileSync(join(dir, f), 'utf8').replace(/\r\n?/g, '\n').trim());
  }
  return `${parts.join('\n')}\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(NOTICES_PATH, buildNotices());
  console.log(`Wrote ${NOTICES_PATH}`);
}

export const noticesExist = () => existsSync(NOTICES_PATH);
