// Writes public/THIRD-PARTY-NOTICES.txt: the copyright notices and licence
// texts of every package shipped in the built site, and of the self-hosted
// fonts. The MIT, ISC, BSD and Apache licences all require their notice to
// accompany redistributed copies, and the minified bundle keeps none of them.
// The file is served with the site at /network/THIRD-PARTY-NOTICES.txt.
//
//   npm run notices
//
// Deterministic: packages are sorted by name, and nothing depends on time or
// on the machine. tests/unit/notices.test.ts fails if the committed file
// differs from what this script would write.

import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const NOTICES_PATH = join(root, 'public', 'THIRD-PARTY-NOTICES.txt');

